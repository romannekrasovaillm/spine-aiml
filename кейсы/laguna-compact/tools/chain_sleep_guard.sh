#!/usr/bin/env bash
# chain_sleep_guard.sh — предполётная защита сна для **отсоединённой цепочки** стадии
# (C-029, AD-9 вторая грань). Ставится первой в записанную команду прогона
# (`chain_command.txt`) и держит защиту все часы стадии.
#
# **Зачем отдельный шаг, а не `systemd-inhibit` прямо в команде.** Так было до
# 21.09.2026, и на стенде `gb10-fast` это работало **против** прогона: инхибит там
# не берётся (`Failed to inhibit: Access denied` — нет logind-сессии), механизм
# отказывает закрыто, и цепочка не стартовала вовсе. Между тем стенд защищён иначе
# и крепче: цели сна замаскированы (`sleep`/`suspend`/`hibernate`/`hybrid-sleep`
# → `/dev/null`, переживает перезагрузку), и это доказано попыткой — `systemctl
# start suspend.target` проваливается с причиной о маскировке. Поэтому шаг
# спрашивает страж (`check_gpu_sleep_guard.py --assert-held`) — тот же вопрос и тот
# же ответ, что у правила C-029 и у обвязки, — и принимает **любой** из двух
# способов: инхибит берётся сам, а если его взять нечем, требуется доказанная
# структурная недостижимость сна на площадке, где цепочка и пойдёт.
#
# **Порядок и отказ.** Инхибит предпочитается: он держится ровно столько, сколько
# живёт нагрузка, и работает на любой машине, а маскировка — свойство конкретной
# площадки. Если не выходит ни то, ни другое, скрипт **не запускает нагрузку**:
# отказ закрытый (exit 2), и цепочка не стартует. Молчаливого незащищённого прогона
# не бывает: сон во время прогона уничтожает контекст CUDA (21.09.2026: S3 в
# 05:03:37 → `Xid 31` в 05:03:44 → смерть прогона V3 на 24-й пробе из 104).
#
# **Причина печатается в `chain.log`**: по ней видно не только «запрет был», но и
# **чем** он держался — иначе о способе пришлось бы догадываться по косвенным.
#
# Метка `CUDA_SLEEP_GUARD=1` ставится нагрузке (не самому шагу): по ней живой
# процесс опознаётся стражем как порождённый санкционированным путём, даже если
# расписка потерялась.
#
# Запуск (так его собирает `tools/launch_sft_stage.py`)::
#
#     bash <run>/chain_sleep_guard.sh bash <run>/pilot_chain.sh --run-dir <run> …
set -uo pipefail

HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CHECKER="$HERE/check_gpu_sleep_guard.py"
WHY="sleep guard: S3 during a CUDA run kills the context (Xid 31)"

if [ $# -eq 0 ]; then
  echo "отказ: не задана полезная нагрузка (после имени скрипта)" >&2
  exit 2
fi

# 1. Инхибит: берём сами, если механизм отвечает. Проверка — самопроверкой на
#    пустой нагрузке, а не «команда есть в PATH»: механизм, который не берётся,
#    обязан отказывать закрыто, и это здесь и выясняется.
if command -v systemd-inhibit >/dev/null 2>&1 \
   && systemd-inhibit --what=sleep --mode=block --why="$WHY" true 2>/dev/null; then
  echo "защита сна: inhibit — инхибит берёт цепочка на всё время прогона"
  exec systemd-inhibit --what=sleep --mode=block --why="$WHY" env CUDA_SLEEP_GUARD=1 "$@"
fi
echo "защита сна: инхибит взять не удалось — спрашиваю страж о площадке" >&2

# 2. Площадка: сон структурно недостижим — доказано попыткой (страж, тот же
#    механизм, что у правила C-029 и у обвязки). Самообъявление не принимается:
#    ответ даёт `--assert-held`, а не «мы знаем, что тут замаскировано».
if [ -f "$CHECKER" ] && python3 "$CHECKER" --assert-held >/dev/null 2>&1; then
  echo "защита сна: площадка — $(python3 "$CHECKER" --assert-held 2>&1)"
  exec env CUDA_SLEEP_GUARD=1 "$@"
fi

# 3. Ни инхибита, ни доказанной недостижимости сна — нагрузка не стартует.
{
  echo "ОТКАЗ: защита сна не доказана ни одним из двух способов."
  [ -f "$CHECKER" ] && python3 "$CHECKER" --assert-held 2>&1 | sed 's/^/  /'
  echo "  Цепочка не запускается: сон во время прогона уничтожает контекст CUDA"
  echo "  (21.09.2026: S3 05:03:37 → Xid 31 05:03:44 → прогон V3 умер на 24-й пробе"
  echo "  из 104, устройство не поднялось). Запуск — через tools/guard_cuda_run.sh."
} >&2
exit 2
