def build_calendar(days_by_wave: dict) -> dict:
    """Календарь области: даты выводятся из длительностей ЗДЕСЬ, а не живут текстом.

    Якорь — точка S4 (**26.09.2026**): это решение `ADR-056` п.5, а не вывод из
    длительности В-0 (от старта 21.09 и 3,8 сут вышло бы 25.09 — расхождение названо,
    а не сглажено). Дальше — арифметика: финиш волны = финиш предыдущей + длительность,
    округлённая ВВЕРХ до целых суток (волна занимает сутки целиком). Волны идут
    последовательно (AD-5), поэтому В-4 стартует от финиша В-1, а не от якоря.
    """
    start = date.fromisoformat(CALENDAR_START)
    deadline = date.fromisoformat(CALENDAR_DEADLINE)
    rows = [{
        "wave": "В-0", "days": days_by_wave["В-0"], "finish": start.isoformat(),
        "derived": False,
        "source": ("ADR-056 п.5 — точка решения S4 (якорь календаря); от старта 21.09 и 3,8 сут "
                   "вышло бы 25.09 — якорь объявлен решением, а не выведен"),
    }]
    cursor = start
    for wave in CALENDAR_AREA:
        d = days_by_wave[wave]
        cursor = cursor + timedelta(days=math.ceil(d - 1e-9))
        rows.append({"wave": wave, "days": d, "finish": cursor.isoformat(), "derived": True,
                     "source": "длительность волны × правило календаря (ceil до целых суток)"})
    finish = cursor
    buffer_days = (deadline - finish).days - 1
    return {
        "start": {"date": CALENDAR_START, "kind": DECISION,
                  "source": "ADR-056 п.5 — точка S4 (В-0); В-1 не стартует раньше (AD-5)"},
        "deadline": {"date": CALENDAR_DEADLINE, "kind": DECISION,
                     "source": "требование владельца 22.09.2026 — уложить область к 1.11 (ADR-056)"},
        "rule": CALENDAR_RULE,
        "buffer_rule": ("полные сутки ПОСЛЕ дня финиша до 1.11: (1.11 − финиш) − 1 (день финиша "
                        "буфером не считается)"),
        "waves": rows,
        "area": list(CALENDAR_AREA),
        "area_finish": finish.isoformat(),
        "buffer_days": buffer_days,
        "within_deadline": finish <= deadline,
        "note": ("В-2/В-3/В-5 датами не обеспечиваются: они отложены за 1.11 решением ADR-056 п.4, "
                 "их длительности — в `waves`, и даты им здесь не выдумываются"),
        "history": [
            {"revision": "ADR-056/S3bj–S3bl", "V1": "2026-10-11", "V4": "2026-10-17",
             "buffer_days": 14,
             "why": ("В-1 ≈14,4 сут и В-4 ≈5,8 сут при плоской цене eval-руки (72,0 и 48,0 ч). "
                     "Историческое, не переписывается (ADR-023 п.9)")},
            {"revision": "S3bm", "V1": rows[1]["finish"], "V4": rows[2]["finish"],
             "buffer_days": buffer_days,
             "why": ("единая модель цены eval-руки: В-1 15,2 сут, В-4 6,4 сут; даты пересчитаны "
                     "заново по правилу календаря (Решение 1 п.3)")},
        ],
    }


