"""spinecalc.logfmt — единый формат логов (AD-2).

Инвариант: ровно одна публичная функция ``format_log``, возвращающая
строку вида ``[LEVEL] msg``. Модуль не выполняет ввода-вывода: никаких
обращений к сети, файловой системе или стандартным потокам.
"""


def format_log(level, msg):
    """Возвращает строку логирования в формате ``[LEVEL] msg``.

    Аргументы:
        level (str): уровень логирования, подставляется в квадратные скобки.
        msg (str): сообщение, отделяется от уровня одним пробелом.

    Возвращает:
        str: строка вида ``"[{level}] {msg}"``.
    """
    return f"[{level}] {msg}"
