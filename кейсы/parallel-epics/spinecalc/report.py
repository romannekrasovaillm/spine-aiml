"""Модуль отчёта: одна строка на сумму (AD-3)."""


def build_report(amounts):
    """Вернуть многострочный отчёт — по одной записи на каждую сумму.

    Каждая сумма форматируется как ``str(value)`` и завершается переводом
    строки, поэтому ``build_report([10.5, 20.0]) == "10.5\\n20.0\\n"``.
    Пустой список даёт пустую строку.
    """
    return "".join(f"{amount}\n" for amount in amounts)
